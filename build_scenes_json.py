try:
    import jsonschema
except ImportError:
    import subprocess
    subprocess.run(["pip", "install", "-q", "jsonschema"], check=True)
    import jsonschema

from jsonschema import Draft202012Validator

with open(SCHEMA_PATH, encoding="utf-8") as f:
    _schema = json.load(f)

# "$schema" is a documentation link for external tools/editors, not part of
# the data validated against our own scenes.schema.json (which models only
# "meta" and "scenes").
_data_to_check = {"meta": OUTPUT["meta"], "scenes": OUTPUT["scenes"]}

Draft202012Validator.check_schema(_schema)
_validator = Draft202012Validator(_schema)
_errors = list(_validator.iter_errors(_data_to_check))

