# Normalize one flag spelling to match the prose exactly everywhere in this
# file (simulate_endings.py has 'اول_عمل' without hamza; the dialogue docx and
# the C2 conditional-opening text both use 'أول_عمل' with hamza). This flag is
# never checked by resolve_ending(), so normalizing it changes no ending logic.
FLAG_NORMALIZE = {"اول_عمل": "أول_عمل"}


def norm_flag(f):
    if f is None:
        return None
    return FLAG_NORMALIZE.get(f, f)


def option_lookup(chapter):
    """Return {code: (delta_dict, flag_or_var)} for a chapter, straight from simulate_endings.py."""
    out = {}
    for code, delta, flag in CHAPTERS[chapter]:
        out[code] = (dict(delta), flag)
    return out


def effects_and_flag(chapter, code):
    """Split a CHAPTERS tuple into (statEffects, flag, setsVariable) for JSON output."""
    delta, flag = option_lookup(chapter)[code]
    sets_variable = None
    out_flag = None
    if flag and "=" in flag:
        var, val = flag.split("=", 1)
        sets_variable = {var: val}
    else:
        out_flag = norm_flag(flag)
    return delta, out_flag, sets_variable


