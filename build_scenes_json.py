def beat(kind, **kw):
    d = {"type": kind}
    d.update(kw)
    return d


def stage(text):
    return beat("stage", text=text)


def narr(text):
    return beat("narr", text=text)


def line(speaker, text):
    return beat("line", speaker=speaker, text=text)


def option(chapter, code, button, response, tags, dev):
    effects, flag, sets_var = effects_and_flag(chapter, code)
    return {
        "code": code,
        "button": button,
        "immediateResponse": response,
        "tagsAr": tags,
        "devNote": dev,
        "effects": effects,
        "flag": flag,
        "setsVariable": sets_var,
    }


